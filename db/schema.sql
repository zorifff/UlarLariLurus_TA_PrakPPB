-- ---------------------------------------------------------------------
-- Tabel master
-- ---------------------------------------------------------------------
create table public.skins (
  id             int generated by default as identity primary key,
  name           text not null unique,
  description    text not null default '',
  head_color     text not null check (head_color ~ '^#[0-9A-Fa-f]{6}$'),
  body_color     text not null check (body_color ~ '^#[0-9A-Fa-f]{6}$'),
  body_color_alt text not null check (body_color_alt ~ '^#[0-9A-Fa-f]{6}$'),
  unlock_score   int  not null default 0 check (unlock_score >= 0),
  sort_order     int  not null default 0
);

create table public.foods (
  id             text primary key check (id ~ '^[a-z_]+$'),
  name           text not null,
  description    text not null default '',
  points         int  not null check (points > 0),
  color          text not null check (color ~ '^#[0-9A-Fa-f]{6}$'),
  spawn_chance   numeric(3,2) not null default 1 check (spawn_chance between 0 and 1),
  lifetime_ticks int check (lifetime_ticks is null or lifetime_ticks > 0),
  is_bonus       boolean not null default false,
  sort_order     int not null default 0
);

-- ---------------------------------------------------------------------
-- Tabel transaksi
-- ---------------------------------------------------------------------
create table public.players (
  id          uuid primary key default gen_random_uuid(),
  username    text not null check (char_length(username) between 3 and 16
                                   and username ~ '^[A-Za-z0-9_]+$'),
  skin_id     int not null default 1 references public.skins(id),
  best_score  int not null default 0 check (best_score >= 0),
  total_games int not null default 0 check (total_games >= 0),
  total_food  int not null default 0 check (total_food >= 0),
  best_score_at timestamptz,
  created_at  timestamptz not null default now()
);
create unique index players_username_lower_idx on public.players (lower(username));
create index players_best_score_idx on public.players (best_score desc, best_score_at asc);

create table public.matches (
  id               uuid primary key default gen_random_uuid(),
  player_id        uuid not null references public.players(id) on delete cascade,
  skin_id          int  not null references public.skins(id),
  score            int  not null check (score >= 0),
  snake_length     int  not null check (snake_length >= 1),
  food_eaten       int  not null default 0 check (food_eaten >= 0),
  duration_seconds int  not null default 0 check (duration_seconds >= 0),
  death_cause      text not null check (death_cause in ('wall', 'self')),
  grid_size        int  not null default 15 check (grid_size between 5 and 50),
  played_at        timestamptz not null default now()
);
create index matches_player_played_idx on public.matches (player_id, played_at desc);

create table public.match_foods (
  match_id uuid not null references public.matches(id) on delete cascade,
  food_id  text not null references public.foods(id),
  quantity int  not null check (quantity > 0),
  primary key (match_id, food_id)
);

-- ---------------------------------------------------------------------
-- Trigger: statistik pemain diupdate dari hasil match
-- ---------------------------------------------------------------------
create function public.apply_match_to_player() returns trigger
language plpgsql set search_path = public as $$
begin
  update public.players p
     set total_games = p.total_games + 1,
         total_food  = p.total_food + new.food_eaten,
         best_score  = greatest(p.best_score, new.score),
         best_score_at = case when new.score > p.best_score then new.played_at else p.best_score_at end
   where p.id = new.player_id;
  return new;
end $$;

create trigger trg_matches_after_insert
after insert on public.matches
for each row execute function public.apply_match_to_player();

-- ---------------------------------------------------------------------
-- View leaderboard
-- ---------------------------------------------------------------------
-- rank di-cast ke int supaya driver mengembalikan number, bukan string (bigint).
create view public.leaderboard as
select (rank() over (order by p.best_score desc))::int as rank,
       p.id, p.username, p.best_score, p.total_games, p.skin_id,
       s.name as skin_name, s.head_color, s.body_color,
       p.best_score_at
  from public.players p
  join public.skins s on s.id = p.skin_id
 where p.best_score > 0
 order by p.best_score desc, p.best_score_at asc;

